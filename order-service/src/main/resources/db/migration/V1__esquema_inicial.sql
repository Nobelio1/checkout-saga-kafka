CREATE TABLE ordenes (
    id                VARCHAR(36)    PRIMARY KEY,
    cliente_id        VARCHAR(60)    NOT NULL,
    lineas_json       TEXT           NOT NULL,
    total             NUMERIC(12, 2) NOT NULL,
    tarjeta_ultimos4  VARCHAR(4)     NOT NULL,
    estado            VARCHAR(20)    NOT NULL,
    motivo            VARCHAR(300),
    idempotency_key   VARCHAR(64)    NOT NULL,
    creada_en         TIMESTAMP      NOT NULL,
    actualizada_en    TIMESTAMP      NOT NULL,
    CONSTRAINT uq_ordenes_idempotency_key UNIQUE (idempotency_key)
);

CREATE INDEX idx_ordenes_cliente ON ordenes (cliente_id);

CREATE TABLE outbox (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topico     VARCHAR(100) NOT NULL,
    clave      VARCHAR(64)  NOT NULL,
    tipo       VARCHAR(200) NOT NULL,
    payload    TEXT         NOT NULL,
    creado_en  TIMESTAMP    NOT NULL,
    publicado  BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_outbox_pendientes ON outbox (id) WHERE publicado = FALSE;
